export interface Faq {
  q: string;
  a: string;
}

/** One row of the symptom → likely cause table. Tables are lifted by answer engines far
 *  more reliably than prose, which is why this is data rather than a paragraph. */
export interface SymptomRow {
  symptom: string;
  cause: string;
}

export interface RelatedService {
  slug: ServiceSlug;
  /** Why these two pages are linked — always a SHARED SYMPTOM, never "here are the others". */
  reason: string;
}

